import * as NodeFSP from "node:fs/promises";
import * as NodeModule from "node:module";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

// Keep native Focus assets and identifiers aligned with the desktop picker.
const root = NodePath.resolve(NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)), "../..");
const require = NodeModule.createRequire(NodePath.join(root, "apps/web/package.json"));
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const icons = require("lucide-react");
const source = await NodeFSP.readFile(
  NodePath.join(root, "apps/web/src/components/focus/FocusIcon.tsx"),
  "utf8",
);
const options = [...source.matchAll(/\{ name: "([^"]+)", label: "([^"]+)", icon: (\w+) \}/g)].map(
  ([, name, label, icon]) => ({ name, label, icon }),
);
if (!options.length) throw new Error("No desktop Focus icon options found.");
const all = [
  ...options,
  { name: "CircleDot", icon: "CircleDotIcon" },
  { name: "Layers3", icon: "Layers3Icon" },
];
const outputs = new Map();
for (const { name, icon } of all) {
  if (!icons[icon]) throw new Error(`Missing Lucide export: ${icon}`);
  const folder = `apps/pathway-ios/Pathway/Assets.xcassets/focus-${name}.imageset`;
  outputs.set(
    `${folder}/icon.svg`,
    renderToStaticMarkup(
      React.createElement(icons[icon], { color: "#000000", width: 24, height: 24 }),
    ) + "\n",
  );
  outputs.set(
    `${folder}/Contents.json`,
    JSON.stringify(
      {
        images: [{ filename: "icon.svg", idiom: "universal" }],
        info: { author: "xcode", version: 1 },
        properties: {
          "preserves-vector-representation": true,
          "template-rendering-intent": "template",
        },
      },
      null,
      2,
    ) + "\n",
  );
}
outputs.set(
  "apps/pathway-ios/Pathway/shared/constants/PathwayFocusIconCatalog.swift",
  `// Generated by scripts/ios/build-focus-icons.mjs from the desktop Focus icon catalog.
enum PathwayFocusIconCatalog {
    struct Option: Identifiable {
        let name: String
        let label: String
        var id: String { name }
    }

    static let options: [Option] = [
${options.map(({ name, label }) => `        .init(name: "${name}", label: "${label}")`).join(",\n")}
    ]
    private static let names = Set(options.map(\\.name) + ["CircleDot", "Layers3"])

    static func assetName(for name: String) -> String {
        "focus-" + (names.contains(name) ? name : "CircleDot")
    }
}
`,
);
outputs.set(
  "apps/pathway-ios/Pathway/Resources/LUCIDE-LICENSE.txt",
  await NodeFSP.readFile(require.resolve("lucide-react/LICENSE"), "utf8"),
);
for (const [relative, contents] of outputs) {
  const output = NodePath.join(root, relative);
  if (process.argv.includes("--check")) {
    if ((await NodeFSP.readFile(output, "utf8")) !== contents)
      throw new Error(`Stale Focus asset: ${relative}`);
  } else {
    await NodeFSP.mkdir(NodePath.dirname(output), { recursive: true });
    await NodeFSP.writeFile(output, contents);
  }
}
console.log(
  `${options.length} desktop Focus icons and native assets ${process.argv.includes("--check") ? "verified" : "generated"}.`,
);
